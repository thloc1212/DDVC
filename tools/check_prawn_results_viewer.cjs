/* Offline browser checks. Usage: node check_prawn_results_viewer.cjs /path/index.html */
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.CHROME_BIN?{executablePath:process.env.CHROME_BIN}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1100},acceptDownloads:true});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  await page.goto(pathToFileURL(process.argv[2]).href);
  await page.waitForFunction(()=>window.viewerDebug?.ids.length>0);
  assert.equal(await page.locator('#dataset option').count(),2);
  assert.ok(await page.locator('#metrics tbody tr').count()>=3);
  const metric=await page.locator('#metrics').innerText();
  const vid=await page.locator('#video').inputValue();
  await page.locator('#search').fill(vid);await page.waitForTimeout(250);
  assert.equal(await page.locator('#video option').count(),1);
  assert.equal(await page.locator('#metrics').innerText(),metric);
  await page.locator('#search').fill('no_such_video_or_caption_abcdefghijklmnopqrstuvwxyz');await page.waitForTimeout(250);
  assert.equal(await page.locator('#video option').count(),0);
  assert.match(await page.locator('#videoTitle').innerText(),/Không có video/);
  await page.locator('#search').fill('');await page.waitForTimeout(250);
  await page.locator('#reviewer').selectOption('a');
  const a=await page.evaluate(()=>viewerDebug.ids);
  await page.locator('#reviewer').selectOption('b');
  const b=await page.evaluate(()=>viewerDebug.ids);
  assert.equal(a.filter(x=>b.includes(x)).length,0);
  assert.equal(a.length+b.length,436);
  await page.locator('#reviewer').selectOption('all');
  await page.locator('#view').selectOption('raw');
  assert.equal(await page.evaluate(()=>viewerDebug.analysis(viewerDebug.ids[0]).a.length),50);
  await page.locator('#view').selectOption('final');
  await page.locator('#timeline rect[data-key]').first().click();
  assert.ok(await page.locator('.event.active').count()>0);
  const download=page.waitForEvent('download');await page.locator('#csv').click();
  assert.match((await download).suggestedFilename(),/yc2.*\.csv$/);
  const caseDownload=page.waitForEvent('download');await page.locator('#caseJSON').click();
  assert.match((await caseDownload).suggestedFilename(),/\.json$/);
  const svgDownload=page.waitForEvent('download');await page.locator('#svg').click();
  assert.match((await svgDownload).suggestedFilename(),/\.svg$/);
  await page.screenshot({path:process.argv[2]+'.yc2.png',fullPage:false});
  await page.locator('#dataset').selectOption('anet');
  assert.equal(await page.locator('#reference option').count(),2);
  assert.equal(await page.locator('#video option').count(),4917);
  await page.locator('#reference').selectOption('1');
  assert.equal(await page.locator('#video option').count(),4885);
  await page.locator('#filter').selectOption('overlap');
  assert.ok(await page.locator('#video option').count()>0);
  await page.locator('#view').selectOption('raw');
  assert.equal(await page.evaluate(()=>viewerDebug.analysis(viewerDebug.ids[0]).b.length),10);
  await page.locator('#view').selectOption('final');
  await page.locator('#threshold').selectOption('0.9');
  await page.locator('#sort').selectOption('miss');
  assert.ok(await page.locator('#timeline svg').count());
  await page.screenshot({path:process.argv[2]+'.anet.png',fullPage:false});
  const matches=await page.evaluate(()=>viewerDebug.match([[0,18],[0,10]],[[0,10],[8,18]],.3).count);
  assert.equal(matches,2);
  assert.deepEqual(errors,[]);
  console.log('PASS offline two-dataset viewer: metrics, search, raw/final, reviewer split, reference pools, overlap, matching, downloads; no browser errors');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
